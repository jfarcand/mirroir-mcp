// ABOUTME: Declares emitted iOS flows in an app dir's SAMPLE.md and its plan entry in .mirroir/mirroir.yaml.
// ABOUTME: Inserts in place into a manifest the emitter owns (marker); hands a human's the lines to paste.

import Foundation

/// The manifest half of the `.mirroir/` emit: `SAMPLE.md` declares every flow
/// under `must_pass`, and `mirroir.yaml` holds a `must_pass` plan entry per app.
///
/// A manifest the emitter created carries an ownership marker, and the emitter
/// keeps it current: every emitted flow and app is inserted into its
/// `must_pass` list in place (`ManifestListInsertion`), so every other byte —
/// a `boot` the web leg filled in, `nice_to_pass`, comments — survives, and
/// nothing declared is removed. A list it cannot locate unambiguously is
/// reported with the lines to paste, never guessed at. A manifest without the
/// marker is a human's, and is never written.
enum MirroirManifestUpsert {

    /// First line of a `SAMPLE.md` the emitter owns. Prose outside the fenced
    /// `yaml` block, which is all `mirroir-run`'s SAMPLE.md loader reads.
    static let sampleOwnershipMarker =
        "<!-- Generated by mirroir-mcp generate_skill (emit: true), which adds every flow it " +
        "emits to must_pass. Delete this line to own the file; it is then never rewritten. -->"

    /// First line of a `mirroir.yaml` the emitter owns: a YAML comment.
    static let planOwnershipMarker =
        "# Generated by mirroir-mcp generate_skill (emit: true), which adds a plan entry for " +
        "every app it emits. Delete this line to own the file; it is then never rewritten."

    /// Declare every one of `scenarios` in the app dir's `SAMPLE.md` under
    /// `must_pass`. Creates `SAMPLE.md` when absent; in an owned one, inserts
    /// the undeclared ones at the end of `session.scenarios.must_pass`.
    ///
    /// - Returns: the note for the result, naming any stale declared flow.
    /// - Throws: `MirroirAppTreeEmitter.EmitError.undeclaredFlows` when a
    ///   `SAMPLE.md` lacks some of `scenarios` and is human-owned, or owned
    ///   with no single `must_pass` block list, with the lines to paste.
    static func upsertSample(appDir: URL, appName: String, scenarios: [String]) throws -> String {
        let samplePath = appDir.appendingPathComponent("SAMPLE.md")
        guard FileManager.default.fileExists(atPath: samplePath.path) else {
            try sampleDocument(appName: appName, entries: scenarios)
                .write(to: samplePath, atomically: true, encoding: .utf8)
            return "created SAMPLE.md declaring \(scenarios.joined(separator: ", "))"
        }
        let existing = try String(contentsOf: samplePath, encoding: .utf8)
        let mustPass = declaredIosScenarios(in: existing, tier: "must_pass")
        let niceToPass = declaredIosScenarios(in: existing, tier: "nice_to_pass")
        let declared = mustPass.union(niceToPass)
        let missing = scenarios.filter { !declared.contains($0) }
        let stale = declared.filter { !scenarios.contains($0) }.sorted()
        let informational = scenarios.filter { niceToPass.contains($0) && !mustPass.contains($0) }
        if missing.isEmpty {
            return "\(scenarios.joined(separator: ", ")) already declared in SAMPLE.md" +
                niceToPassNote(informational) + staleNote(stale)
        }
        guard isOwned(existing, marker: sampleOwnershipMarker),
              let block = ManifestListInsertion.fencedYamlBlock(in: existing),
              let updated = ManifestListInsertion.insert(
                into: existing, lines: block, keyPath: ["session", "scenarios", "must_pass"],
                items: missing.map { ["- \($0)"] })
        else {
            throw MirroirAppTreeEmitter.EmitError.undeclaredFlows(
                sample: samplePath.path, undeclared: missing,
                snippet: missing.map { "      - \($0)" }.joined(separator: "\n"),
                stale: stale, dropped: [], planError: nil)
        }
        try updated.write(to: samplePath, atomically: true, encoding: .utf8)
        return "added \(missing.joined(separator: ", ")) to SAMPLE.md must_pass" +
            niceToPassNote(informational) + staleNote(stale)
    }

    /// Add a `local:` plan entry for `slug` under `plan.must_pass`. Creates
    /// `mirroir.yaml` when absent and inserts at the end of an owned one's
    /// `plan.must_pass` list; a human-owned one gets a copy-paste snippet in
    /// the returned note.
    ///
    /// - Throws: `MirroirAppTreeEmitter.EmitError.unplacedPlanEntry` when an
    ///   owned `mirroir.yaml` has no single `plan.must_pass` block list.
    static func upsertPlan(mirroirRoot: URL, slug: String) throws -> String {
        let planPath = mirroirRoot.appendingPathComponent("mirroir.yaml")
        let item = [
            "- name: \(slug)",
            "  local: apps/\(slug)",
            "  boot:",
            "    command: \"true\"",
        ]
        let entry = item.map { "    " + $0 }.joined(separator: "\n")

        guard FileManager.default.fileExists(atPath: planPath.path) else {
            let doc = planOwnershipMarker + "\nversion: 1\nplan:\n  must_pass:\n" + entry + "\n"
            try doc.write(to: planPath, atomically: true, encoding: .utf8)
            return "created .mirroir/mirroir.yaml with plan entry '\(slug)'"
        }
        let existing = try String(contentsOf: planPath, encoding: .utf8)
        let named = ManifestListInsertion.mappingValues(
            "name", in: existing, lines: ManifestListInsertion.wholeDocument(existing),
            keyPath: ["plan", "must_pass"]) ?? []
        if named.contains(slug) {
            return "plan entry '\(slug)' already present in mirroir.yaml"
        }
        guard isOwned(existing, marker: planOwnershipMarker) else {
            return "add this entry to .mirroir/mirroir.yaml under plan.must_pass:\n\(entry)"
        }
        guard let updated = ManifestListInsertion.insert(
            into: existing, lines: ManifestListInsertion.wholeDocument(existing),
            keyPath: ["plan", "must_pass"], items: [item]) else {
            throw MirroirAppTreeEmitter.EmitError.unplacedPlanEntry(
                plan: planPath.path, slug: slug, snippet: entry)
        }
        try updated.write(to: planPath, atomically: true, encoding: .utf8)
        return "added plan entry '\(slug)' to .mirroir/mirroir.yaml"
    }

    /// Every iOS scenario (`*.ios.yaml`) `sample` declares under
    /// `session.scenarios.<tier>` of its fenced yaml block — the list
    /// `mirroir-run` reads. A path in a comment, in prose, or under a key the
    /// runner does not read is not declared.
    static func declaredIosScenarios(in sample: String, tier: String) -> Set<String> {
        guard let block = ManifestListInsertion.fencedYamlBlock(in: sample),
              let entries = ManifestListInsertion.scalarItems(
                in: sample, lines: block, keyPath: ["session", "scenarios", tier])
        else { return [] }
        return Set(entries.filter { $0.hasSuffix(".ios.yaml") })
    }

    /// The trailing note naming emitted flows declared only under
    /// `nice_to_pass`, whose FAIL does not fail the sample.
    static func niceToPassNote(_ flows: [String]) -> String {
        guard !flows.isEmpty else { return "" }
        return "\nSAMPLE.md declares \(flows.joined(separator: ", ")) under nice_to_pass " +
            "only, so a FAIL there does not fail the sample; move them to must_pass to gate on them"
    }

    /// The trailing note naming declared iOS flows an emit did not produce.
    static func staleNote(_ stale: [String]) -> String {
        guard !stale.isEmpty else { return "" }
        return "\nSAMPLE.md also declares \(stale.joined(separator: ", ")), which this " +
            "exploration did not produce; they stay on disk and declared — remove them " +
            "from SAMPLE.md if the flow no longer exists"
    }

    // MARK: - Private

    /// Whether `document` carries `marker` as one of its lines.
    private static func isOwned(_ document: String, marker: String) -> Bool {
        document.split(separator: "\n").contains { $0 == marker }
    }

    /// The whole `SAMPLE.md` the emitter owns, declaring `entries` under `must_pass`.
    private static func sampleDocument(appName: String, entries: [String]) -> String {
        let list = entries.map { "      - \($0)" }.joined(separator: "\n")
        return """
            \(sampleOwnershipMarker)
            # \(appName)

            The iOS flows `generate_skill` recorded for this app. Each runs as
            one `target: { kind: ios }` block through `mirroir-mcp test`; the
            app needs no server, so the boot command starts nothing.

            ```yaml
            version: 1
            session:
              boot:
                command: "true"
              scenarios:
                must_pass:
            \(list)
            ```

            """
    }
}
