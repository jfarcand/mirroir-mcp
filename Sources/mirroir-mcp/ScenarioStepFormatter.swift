// ABOUTME: Formats a linear iOS exploration capture into a mirroir-run SkillStep scenario (YAML).
// ABOUTME: Pure transformation — emits target/reset_app/launch/tap/wait_for/... steps and renders OCR text.

import Foundation
import HelperLib

/// Renders a linear exploration capture into a `mirroir-run` SkillStep scenario
/// on the iOS surface, and a screen's OCR text for a live capture.
///
/// The emitted YAML is written in the shared step grammar and opens
/// `target: { kind: ios }`: mirroir-run hands that block to `mirroir-mcp test`
/// on a macOS host, and this binary's own parser reads it the same way. Every
/// captured action becomes a step or a refusal — a walk is never shortened.
enum ScenarioStepFormatter {

    /// Errors raised when a capture cannot be rendered faithfully. Each names
    /// the walk index of the screen the offending action reached.
    enum FormatError: LocalizedError, Equatable {
        /// The capture recorded an action type the scenario grammar has no step for.
        case unsupportedAction(index: Int, action: String)
        /// The capture recorded an AI-only step (`SkillParser.aiOnlyStepTypes`):
        /// mirroir-run refuses it inside an `ios` block, so the walk cannot hold it.
        case aiOnlyAction(index: Int, action: String)
        /// An element action recorded no label to act on.
        case unlabeledAction(index: Int, action: String)
        /// An element action's label is on the exclusion list (`text-cleanup.md`).
        case excludedLabel(index: Int, action: String, label: String)
        /// A literal action (typed text, key, direction, URL, name) recorded no value.
        case emptyValue(index: Int, action: String)
        /// An element action's label is not among the OCR text of the screen
        /// it acts on — an icon-only tab named from APP.md, say — so a replay
        /// that looks for it there could never find it.
        case labelNotOnScreen(index: Int, action: String, label: String)

        var errorDescription: String? {
            switch self {
            case .unsupportedAction(let index, let action):
                return "step \(index): captured action_type \"\(action)\" has no scenario step; " +
                    "refusing to record it as a different action"
            case .aiOnlyAction(let index, let action):
                return "step \(index): \"\(action)\" is an AI-only step mirroir-run refuses " +
                    "inside an ios block; refusing to emit a walk that cannot replay"
            case .unlabeledAction(let index, let action):
                return "step \(index): \(action) recorded no label; refusing to emit a walk " +
                    "that skips it"
            case .excludedLabel(let index, let action, let label):
                return "step \(index): \(action) label \"\(label)\" is excluded by " +
                    "text-cleanup.md; refusing to emit a walk that skips it"
            case .emptyValue(let index, let action):
                return "step \(index): \(action) recorded no value; refusing to emit a walk " +
                    "that skips it"
            case .labelNotOnScreen(let index, let action, let label):
                return "step \(index): \(action) label \"\(label)\" is not in the OCR text of " +
                    "the screen it acts on; refusing to emit a step a replay cannot find"
            }
        }
    }

    /// The first line of every emitted scenario: the emitter owns the file.
    static let generatedHeader =
        "# Generated by mirroir-mcp generate_skill (emit: true); re-emitting this flow overwrites this file."

    /// Every step verb this formatter can write, in the order the shared
    /// golden walk exercises them. The runner's contract test renders each.
    static let emittedVerbs: [String] = [
        "target", "reset_app", "launch", "tap", "wait_for", "long_press", "scroll_to",
        "assert_visible", "assert_not_visible", "type", "press_key", "swipe",
        "open_url", "screenshot", "home",
    ]

    /// Build the full `<flow>.ios.yaml` scenario document for `screens`.
    /// The first screen is the launch, preceded by a `reset_app:` of the same
    /// app: launching a running app resumes wherever it was left, and the walk
    /// was recorded from the app's root. That own-app reset right before its
    /// launch is the one `reset_app` `DestructiveStepGate` lets run without
    /// `--confirm-destructive`. Each subsequent screen contributes the
    /// action that reached it. A tap or long press that arrives on a screen
    /// with a landmark of its own is followed by a `wait_for:` on it, and a
    /// destination landmark assertion closes the walk. A tap or long press on
    /// a row the explorer reached by scrolling the screen it acted on is
    /// preceded by a `scroll_to:` on that row, since a replay lands on the
    /// arrival viewport and does not scroll for a tap. Landmarks come only from
    /// the viewport a screen showed on arrival (`ExploredScreen.arrivalElements`):
    /// a row calibration found by scrolling is not on screen when a replay's
    /// tap lands, so waiting for it would time out.
    ///
    /// - Throws: `FormatError` when a screen was reached by an action the
    ///   scenario cannot carry faithfully.
    static func scenarioYAML(name: String, appName: String, screens: [ExploredScreen]) throws -> String {
        var steps: [String] = [
            "  - target: { kind: ios, app: \(yamlScalar(appName)) }",
            "  - reset_app: \(yamlScalar(appName))",
            "  - launch: \(yamlScalar(appName))",
        ]
        for (index, screen) in screens.enumerated().dropFirst() {
            let source = screens[index - 1]
            steps.append(contentsOf: try stepLines(index: index, screen: screen, source: source))
            let action = screen.actionType ?? "tap"
            if arrivalActions.contains(action),
               let arrived = landmark(in: screen.arrivalElements, absentFrom: source.elements) {
                steps.append("  - wait_for: \(yamlScalar(arrived))")
            }
        }
        if let destination = landmark(in: screens.last?.arrivalElements ?? [], absentFrom: []) {
            let assertion = "  - assert_visible: \(yamlScalar(destination))"
            if steps.last != "  - wait_for: \(yamlScalar(destination))" {
                steps.append(assertion)
            }
        }
        return generatedHeader + "\n" +
            "version: 1\nname: \(yamlScalar(name))\nsteps:\n" + steps.joined(separator: "\n") + "\n"
    }

    /// Whitespace-joined OCR text of one screen — what an iOS block's live
    /// capture carries into a `cross_surface:` comparison.
    static func screenText(elements: [TapPoint]) -> String {
        let tokens = elements
            .map(\.text)
            .filter { !$0.isEmpty }
        return tokens.joined(separator: " ") + "\n"
    }

    // MARK: - Private

    /// Actions whose value names an on-screen element. The recorded label came
    /// from OCR, so it is cleaned, checked against the exclusion list, and
    /// matched to the element's exact casing on the screen it acted on — the
    /// screen before the one it reached, except for `scrollToActions`.
    private static let elementActions: Set<String> = [
        "tap", "long_press", "scroll_to", "assert_visible",
    ]

    /// Element actions whose label is on the screen they REACHED: a scroll
    /// brings its target into view, so the screen before it need not show it.
    private static let scrollToActions: Set<String> = ["scroll_to"]

    /// Element actions that navigate: replay waits for the screen they reached.
    private static let arrivalActions: Set<String> = ["tap", "long_press"]

    /// Actions whose value is carried verbatim: typed text, a key, a swipe
    /// direction, a URL, a screenshot name, or a label asserted ABSENT
    /// (which by definition is not on the screen to be matched against).
    private static let literalActions: Set<String> = [
        "type", "press_key", "swipe", "open_url", "screenshot",
        "assert_not_visible",
    ]

    /// Map the action that reached `screen` (from `source`) into its
    /// SkillStep YAML nodes: one, or a `scroll_to:` then the tap or long press
    /// when its label sits only in the rows scrolling merged into `source`.
    ///
    /// - Throws: `FormatError` for an AI-only or unsupported action, an
    ///   element action with no usable label, or a literal action with no
    ///   value — writing anything else would record a walk that never happened.
    private static func stepLines(index: Int, screen: ExploredScreen, source: ExploredScreen) throws -> [String] {
        let action = screen.actionType ?? "tap"
        if action == "press_home" {
            return ["  - home:"]
        }
        if SkillParser.aiOnlyStepTypes.contains(action) {
            throw FormatError.aiOnlyAction(index: index, action: action)
        }
        if elementActions.contains(action) {
            // The text actually acted on wins over the display label: a display
            // label can name what OCR never read (an icon-only tab's APP.md name).
            guard let rawLabel = [screen.arrivedVia, screen.displayLabel]
                .compactMap({ $0 }).first(where: { !$0.isEmpty }) else {
                throw FormatError.unlabeledAction(index: index, action: action)
            }
            let clean = ActionStepFormatter.cleanLabel(rawLabel)
            guard !clean.isEmpty else {
                throw FormatError.unlabeledAction(index: index, action: action)
            }
            guard !ActionStepFormatter.isExcludedLabel(clean) else {
                throw FormatError.excludedLabel(index: index, action: action, label: clean)
            }
            let actedOn = scrollToActions.contains(action) ? screen : source
            guard let label = onScreenLabel(clean, elements: actedOn.elements) else {
                throw FormatError.labelNotOnScreen(index: index, action: action, label: clean)
            }
            let step = "  - \(action): \(yamlScalar(label))"
            if arrivalActions.contains(action),
               onScreenLabel(clean, elements: source.arrivalElements) == nil {
                return ["  - scroll_to: \(yamlScalar(label))", step]
            }
            return [step]
        }
        if literalActions.contains(action) {
            guard let value = screen.arrivedVia, !value.isEmpty else {
                throw FormatError.emptyValue(index: index, action: action)
            }
            return ["  - \(action): \(yamlScalar(value))"]
        }
        throw FormatError.unsupportedAction(index: index, action: action)
    }

    /// The OCR text of the element `label` names on a screen, in the casing
    /// OCR read it: an exact match, else one equal ignoring case or cleanup
    /// prefixes. No containment match — "Every" is a different control from
    /// "Every Sunday" — and no fallback: nil when the screen does not show it.
    private static func onScreenLabel(_ label: String, elements: [TapPoint]) -> String? {
        if elements.contains(where: { $0.text == label }) {
            return label
        }
        let lowered = label.lowercased()
        return elements.first(where: {
            ActionStepFormatter.cleanLabel($0.text).lowercased() == lowered
        })?.text
    }

    /// Pick a landmark: the longest non-excluded label of `elements` that
    /// `absentFrom` does not also show (prominence-by-length, mirroring
    /// `LandmarkPicker`). The first such label in screen order wins a tie. Only
    /// structural text counts: the status bar, times, bare numbers, dates and long
    /// paragraphs change between runs, so a wait on them proves nothing.
    private static func landmark(in elements: [TapPoint], absentFrom: [TapPoint]) -> String? {
        let shared = Set(absentFrom.map { ActionStepFormatter.cleanLabel($0.text) })
        var best: String?
        for element in elements where StructuralFingerprint.passesStructuralFilter(element) {
            let label = ActionStepFormatter.cleanLabel(element.text)
            guard label.count >= 3, !ActionStepFormatter.isExcludedLabel(label),
                  !shared.contains(label) else { continue }
            if label.count > (best?.count ?? 0) {
                best = label
            }
        }
        return best
    }

    /// Quote a value as a double-quoted YAML scalar, escaping `"`, `\`, and newlines.
    private static func yamlScalar(_ s: String) -> String {
        var out = "\""
        for c in s {
            switch c {
            case "\"": out += "\\\""
            case "\\": out += "\\\\"
            case "\n": out += "\\n"
            default: out.append(c)
            }
        }
        return out + "\""
    }
}
